import type {
  Card,
  CardCategory,
  CardEffect,
  Cycle,
  DisasterId,
  MeterKey,
  PermanentModifiers,
  RationKind,
} from '../types';

const DECK_CYCLES: Record<CardCategory, Cycle[]> = {
  daily: ['morning'],
  research: ['afternoon'],
  exploration: ['afternoon'],
  build: ['evening'],
  upgrade: ['evening'],
  repair: [],
};

const meter = (key: MeterKey, delta: number): CardEffect => ({
  meter: key,
  delta,
});

const ration = (kind: RationKind, delta: number): CardEffect => ({
  ration: kind,
  rationDelta: delta,
});

const heal = (
  from: CardEffect['fromCondition'],
  target: CardEffect['conditionTarget'] = 'assigned',
  count = 1,
): CardEffect => ({
  fromCondition: from,
  condition: 'ready',
  conditionTarget: target,
  conditionCount: count,
});

function makeCard(
  card: Omit<Card, 'cycles' | 'costs' | 'effects' | 'rejectionPenalty' | 'recommendedCrewIds'> &
    Partial<
      Pick<
        Card,
        'cycles' | 'costs' | 'effects' | 'rejectionPenalty' | 'recommendedCrewIds'
      >
    >,
): Card {
  return {
    cycles: DECK_CYCLES[card.category],
    costs: [],
    effects: [],
    rejectionPenalty: [],
    recommendedCrewIds: [],
    ...card,
  };
}

function daily(
  id: string,
  name: string,
  description: string,
  input: Partial<Card> & {
    durationCycles: number;
    requiresCrew: boolean;
    validitySol: number;
    fact: string;
    source: string;
    limit: string;
  },
): Card {
  return makeCard({
    id,
    name,
    description,
    deck: 'daily',
    category: 'daily',
    ...input,
  });
}

function mission(
  deck: Exclude<CardCategory, 'daily' | 'repair'>,
  id: string,
  name: string,
  description: string,
  input: Partial<Card> & {
    durationCycles: number;
    requiresCrew: boolean;
    fact: string;
    source: string;
    limit: string;
  },
): Card {
  return makeCard({
    id,
    name,
    description,
    deck,
    category: deck,
    ...input,
  });
}

function repair(
  disasterId: DisasterId,
  id: string,
  name: string,
  description: string,
  input: Partial<Card> & {
    durationCycles: number;
    requiresCrew: boolean;
    fact: string;
    source: string;
    limit: string;
  },
): Card {
  return makeCard({
    id,
    name,
    description,
    deck: 'repair',
    category: 'repair',
    disasterId,
    ...input,
  });
}

